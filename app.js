// ================= CALENDAR =================
function renderCalendar() {
  const calDays = document.getElementById('calendarDays');
  calDays.innerHTML = '';
  const events = currentData.calendarEvents || {};

  // September starts on Tuesday (day 2)
  const pad = document.createElement('div');
  pad.className = 'cal-day-cell bg-slate-50/50 border-transparent';
  calDays.appendChild(pad);

  for (let day = 1; day <= 30; day++) {
    const dayCell = document.createElement('div');
    dayCell.className = 'cal-day-cell';
    const dayEvents = events[day] || [];

    let eventHtml = '';
    if (dayEvents.length > 0) {
      eventHtml = dayEvents.map(ev => {
        if (ev.highlight) {
          return `
            <div class="cal-event-badge bg-rose-600 text-white font-bold flex items-center gap-0.5">
              <span class="w-1.5 h-1.5 rounded-full bg-white inline-block"></span>
              <span class="truncate">${ev.title}</span>
            </div>
          `;
        }
        const colorClass = ev.color === 'blue' ? 'bg-blue-50 text-blue-700 border border-blue-200' : 'bg-amber-50 text-amber-700 border border-amber-200';
        return `
          <div class="cal-event-badge ${colorClass} flex items-center gap-0.5">
            <span class="w-1 h-1 rounded-full ${ev.color === 'blue' ? 'bg-blue-500' : 'bg-amber-500'} inline-block"></span>
            <span class="truncate">${ev.title}</span>
          </div>
        `;
      }).join('');
    }

    dayCell.innerHTML = `
      <span class="cal-day-num ${dayEvents.length > 0 && dayEvents[0].highlight ? 'text-rose-600 font-bold' : ''}">${day}</span>
      ${eventHtml}
    `;
    calDays.appendChild(dayCell);
  }
}

